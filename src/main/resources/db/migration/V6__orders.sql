CREATE SEQUENCE order_id_seq START WITH 1;
CREATE SEQUENCE order_payment_key_seq START WITH 100000;
CREATE TABLE orders (
    id bigint PRIMARY KEY DEFAULT nextval('order_id_seq'),
    member_id bigint NOT NULL REFERENCES members(id),
    idempotency_key varchar(200) NOT NULL,
    canonical_request text NOT NULL,
    order_no varchar(80) UNIQUE,
    payment_key bigint UNIQUE,
    status varchar(30) NOT NULL DEFAULT 'PAYMENT_PENDING' CHECK (status IN ('PAYMENT_PENDING','PAID','FAILED','CANCELLED')),
    total_product_amount numeric(19,2), raw_discount_amount numeric(24,8), discount_amount numeric(19,0),
    point_used_amount numeric(19,0), delivery_fee numeric(19,0), final_payment_amount numeric(19,0),
    member_coupon_id bigint, delivery_address_id bigint,
    recipient_name varchar(100), phone varchar(30), zipcode varchar(20), address_main varchar(500), address_detail varchar(500),
    created_at timestamptz NOT NULL,
    UNIQUE(member_id, idempotency_key)
);
CREATE INDEX idx_orders_member_created ON orders(member_id, created_at DESC, id DESC);
CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(id), position integer NOT NULL,
    product_id bigint NOT NULL, product_option_id bigint NOT NULL,
    product_name varchar(200) NOT NULL, option_name varchar(100) NOT NULL,
    unit_price numeric(19,2) NOT NULL, quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    total_amount numeric(19,2) NOT NULL, option_status varchar(20) NOT NULL, available_quantity bigint,
    UNIQUE(order_id,position)
);
CREATE TABLE order_cart_items (
    order_id bigint NOT NULL REFERENCES orders(id), cart_item_id bigint NOT NULL,
    PRIMARY KEY(order_id,cart_item_id)
);
