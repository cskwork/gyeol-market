-- Each module owns its identifiers; catalog/member access goes through public APIs.
CREATE TABLE cart_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL, option_id bigint NOT NULL,
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    version bigint NOT NULL DEFAULT 0, UNIQUE(member_id, option_id)
);
CREATE INDEX idx_cart_member ON cart_items(member_id, id);
CREATE TABLE cart_guest_sessions (
    session_hash varchar(64) PRIMARY KEY, claimed_by bigint
);
CREATE TABLE cart_guest_items (
    session_hash varchar(64) REFERENCES cart_guest_sessions(session_hash),
    option_id bigint NOT NULL, quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    PRIMARY KEY(session_hash, option_id)
);
CREATE TABLE addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, member_id bigint NOT NULL,
    recipient_name varchar(100) NOT NULL, phone varchar(20) NOT NULL,
    zipcode varchar(10) NOT NULL, address_main varchar(255) NOT NULL,
    address_detail varchar(255), is_default boolean NOT NULL
);
CREATE INDEX idx_addresses_member ON addresses(member_id, id);
CREATE UNIQUE INDEX idx_addresses_one_default ON addresses(member_id) WHERE is_default;
CREATE TABLE wishlist_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL, product_id bigint NOT NULL, UNIQUE(member_id, product_id)
);
CREATE INDEX idx_wishlist_member ON wishlist_items(member_id, id DESC);
