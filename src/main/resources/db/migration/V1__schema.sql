CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE brand (
    id bigint PRIMARY KEY, name varchar(100) NOT NULL, slug varchar(100) UNIQUE NOT NULL, logo_url varchar(500)
);
CREATE TABLE category (
    id bigint PRIMARY KEY, parent_id bigint REFERENCES category(id), name varchar(100) NOT NULL,
    slug varchar(100) UNIQUE NOT NULL, sort_order integer NOT NULL
);
CREATE INDEX idx_category_parent ON category(parent_id, sort_order);
CREATE TABLE product (
    id bigint PRIMARY KEY, brand_id bigint NOT NULL REFERENCES brand(id), name varchar(200) NOT NULL,
    description text, base_price numeric(19,2) NOT NULL CHECK (base_price >= 0),
    sale_price numeric(19,2) NOT NULL CHECK (sale_price >= 0 AND sale_price <= base_price), created_order bigint NOT NULL
);
CREATE INDEX idx_product_brand ON product(brand_id);
CREATE INDEX idx_product_created ON product(created_order DESC);
CREATE TABLE product_category (
    product_id bigint REFERENCES product(id), category_id bigint REFERENCES category(id), PRIMARY KEY(product_id, category_id)
);
CREATE INDEX idx_product_category_category ON product_category(category_id, product_id);
CREATE TABLE product_option (
    id bigint PRIMARY KEY, product_id bigint NOT NULL REFERENCES product(id), name varchar(100) NOT NULL,
    price numeric(19,2) NOT NULL CHECK (price >= 0), status varchar(20) NOT NULL CHECK (status IN ('ON_SALE','SOLD_OUT','STOPPED','HIDDEN')),
    available_quantity bigint CHECK (available_quantity >= 0), sort_order integer NOT NULL
);
CREATE INDEX idx_product_option_product ON product_option(product_id, sort_order);
CREATE TABLE product_image (
    id bigint PRIMARY KEY, product_id bigint NOT NULL REFERENCES product(id), url varchar(500) NOT NULL,
    sort_order integer NOT NULL, is_thumbnail boolean NOT NULL
);
CREATE INDEX idx_product_image_product ON product_image(product_id, sort_order);
CREATE UNIQUE INDEX idx_product_one_thumbnail ON product_image(product_id) WHERE is_thumbnail;
CREATE TABLE product_review (
    id bigint PRIMARY KEY, product_id bigint NOT NULL REFERENCES product(id), member_name varchar(100) NOT NULL,
    rating numeric(2,1) NOT NULL CHECK (rating >= 0 AND rating <= 5), title text, content text NOT NULL,
    image_urls jsonb, created_at timestamptz NOT NULL
);
CREATE INDEX idx_product_review_product ON product_review(product_id, created_at DESC, id DESC);

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(512) NOT NULL, name VARCHAR(100) NOT NULL, phone VARCHAR(20), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE refresh_families (
    id UUID PRIMARY KEY, member_id BIGINT NOT NULL REFERENCES members(id), expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_refresh_families_member ON refresh_families(member_id);
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, family_id UUID NOT NULL REFERENCES refresh_families(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE, expires_at TIMESTAMPTZ NOT NULL, consumed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens(family_id);

-- This projection owns its data and deliberately has no foreign key into catalog.
CREATE TABLE search_documents (
    product_id bigint PRIMARY KEY, brand_id bigint NOT NULL, brand_name text, product_name text NOT NULL,
    description text NOT NULL DEFAULT '', sale_price numeric(19,2) NOT NULL, original_price numeric(19,2) NOT NULL,
    discount_rate numeric(10,2) NOT NULL, rating numeric(20,16) NOT NULL CHECK (rating >= 0 AND rating <= 5), review_count bigint NOT NULL CHECK (review_count >= 0), thumbnail_url text, category_ids bigint[] NOT NULL DEFAULT '{}', created_order bigint NOT NULL,
    search_vector tsvector GENERATED ALWAYS AS (
        to_tsvector('simple'::regconfig, coalesce(product_name,'') || ' ' || coalesce(description,'') || ' ' || coalesce(brand_name,''))
    ) STORED
);
CREATE INDEX idx_search_full_text ON search_documents USING gin(search_vector);
CREATE INDEX idx_search_product_name ON search_documents USING gin(lower(product_name) gin_trgm_ops);
CREATE INDEX idx_search_description ON search_documents USING gin(lower(description) gin_trgm_ops);
CREATE INDEX idx_search_brand_name ON search_documents USING gin(lower(brand_name) gin_trgm_ops);
CREATE INDEX idx_search_autocomplete ON search_documents USING gin(product_name gin_trgm_ops);
CREATE INDEX idx_search_categories ON search_documents USING gin(category_ids);
