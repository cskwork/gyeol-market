CREATE TABLE coupon (
    id bigint PRIMARY KEY,
    name varchar(100) NOT NULL,
    discount_type varchar(30) NOT NULL CHECK (discount_type IN ('FIXED_AMOUNT', 'PERCENTAGE', 'FREE_SHIPPING')),
    discount_value numeric(19,2) NOT NULL CHECK (discount_value >= 0),
    min_order_amount numeric(19,2) NOT NULL CHECK (min_order_amount >= 0)
);

CREATE TABLE member_coupon (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES members(id),
    coupon_id bigint NOT NULL REFERENCES coupon(id),
    status varchar(20) NOT NULL CHECK (status IN ('ISSUED', 'USED', 'EXPIRED', 'REVOKED')),
    issued_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    reserved_order_id bigint,
    UNIQUE (member_id, coupon_id),
    CHECK (expires_at > issued_at)
);
CREATE INDEX idx_member_coupon_status ON member_coupon(member_id, status);

